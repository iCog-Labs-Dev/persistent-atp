"""Receiver protocol. Implementations bind credentials outside request DTOs."""
from __future__ import annotations

from typing import Any, Protocol

from .models import ActionRequest, Admission, CapabilitySet, CoordinationPage, Event, OperationRef, OperationSnapshot, ProjectDigest


class ReceiverPort(Protocol):
    async def capabilities(self, *, contract_version: str = "2.0") -> CapabilitySet: ...
    async def submit(self, request: ActionRequest) -> Admission: ...
    async def lookup_request(self, workspace_id: str, request_id: str) -> Admission | None: ...
    async def get_operation(self, ref: OperationRef) -> OperationSnapshot: ...
    async def list_operations(self, *, workspace_id: str, proof_id: str | None = None, active_only: bool = True, cursor: str | None = None) -> tuple[OperationSnapshot, ...]: ...
    async def read_status(self, *, workspace_id: str, proof_id: str, at_revision: int | None = None) -> ProjectDigest: ...
    async def read_coordination(self, *, workspace_id: str, proof_id: str, cursor: str | None = None, page_size: int = 100) -> CoordinationPage: ...
    async def read_events(self, ref: OperationRef, cursor: str | None = None) -> tuple[tuple[Event, ...], str | None]: ...
    async def cancel(self, control: Any) -> Any: ...
    async def amend_budget(self, control: Any) -> Any: ...
    async def answer_decision(self, control: Any) -> Any: ...
    async def put_artifact(self, source: Any, *, workspace_id: str, media_type: str, expected_hash: str | None = None) -> Any: ...
    async def get_artifact(self, ref: Any, *, workspace_id: str) -> bytes: ...
    async def aclose(self) -> None: ...
